package com.example.javaw.reference;

import jakarta.persistence.*;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.boot.SpringBootConfiguration;
import org.springframework.boot.WebApplicationType;
import org.springframework.boot.autoconfigure.EnableAutoConfiguration;
import org.springframework.boot.autoconfigure.domain.EntityScan;
import org.springframework.boot.builder.SpringApplicationBuilder;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.config.EnableJpaRepositories;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;

import java.math.BigDecimal;
import java.nio.file.Path;
import java.sql.*;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;

/** JVM oracle for the pinned real libraries; these are not Wasm compatibility claims. */
class RuntimeReferenceTest {
    @TempDir Path temporary;

    @Test void actualH2JdbcTransactionsAndFileReopen() throws Exception {
        String url = "jdbc:h2:" + temporary.resolve("reference").toAbsolutePath();
        try (Connection connection = DriverManager.getConnection(url, "sa", "")) {
            assertEquals("2.2.224 (2023-09-17)", connection.getMetaData().getDatabaseProductVersion());
            connection.createStatement().execute("create table products(id bigint generated by default as identity primary key, name varchar(100) unique, price decimal(38,8))");
            connection.setAutoCommit(false);
            try (PreparedStatement insert = connection.prepareStatement("insert into products(name,price) values (?,?)", Statement.RETURN_GENERATED_KEYS)) {
                insert.setString(1, "雪"); insert.setBigDecimal(2, new BigDecimal("9007199254740993.12345678"));
                assertEquals(1, insert.executeUpdate());
                try (ResultSet keys = insert.getGeneratedKeys()) { assertTrue(keys.next()); assertTrue(keys.getLong(1) > 0); }
                Savepoint point = connection.setSavepoint();
                insert.setString(1, "rollback"); insert.setNull(2, Types.DECIMAL); insert.executeUpdate();
                connection.rollback(point); connection.commit();
                insert.setString(1, "雪");
                assertThrows(SQLException.class, insert::executeUpdate);
                connection.rollback();
            }
        }
        try (Connection connection = DriverManager.getConnection(url, "sa", "");
             ResultSet result = connection.createStatement().executeQuery("select name,price from products")) {
            assertTrue(result.next()); assertEquals("雪", result.getString(1));
            assertEquals(new BigDecimal("9007199254740993.12345678"), result.getBigDecimal(2));
            assertFalse(result.next());
        }
    }

    @SpringBootConfiguration
    @EnableAutoConfiguration
    @EntityScan(basePackageClasses = RuntimeReferenceTest.class)
    @EnableJpaRepositories(basePackageClasses = RuntimeReferenceTest.class, considerNestedRepositories = true)
    static class ReferenceConfiguration {}

    @Entity(name = "RuntimeProduct")
    @Table(name = "runtime_products")
    public static class RuntimeProduct {
        @Id @GeneratedValue(strategy = GenerationType.IDENTITY) public Long id;
        @Version public int version;
        @Column(nullable = false, unique = true) public String name;
        @Column(precision = 38, scale = 8) public BigDecimal price;
        public RuntimeProduct() {}
        RuntimeProduct(String name) { this.name = name; this.price = new BigDecimal("9007199254740993.12345678"); }
    }

    interface Products extends JpaRepository<RuntimeProduct, Long> {
        Optional<RuntimeProduct> findByName(String name);
    }

    @Test void actualSpringHibernateRepositoryStartupTransactionsAndShutdown() {
        try (var context = new SpringApplicationBuilder(ReferenceConfiguration.class).web(WebApplicationType.NONE)
                .properties("spring.datasource.url=jdbc:h2:mem:javaw_reference", "spring.datasource.username=sa",
                        "spring.jpa.hibernate.ddl-auto=create-drop", "spring.main.banner-mode=off",
                        "spring.jmx.enabled=false", "logging.level.root=WARN").run()) {
            assertEquals("3.2.4", org.springframework.boot.SpringBootVersion.getVersion());
            assertEquals("6.1.5", org.springframework.core.SpringVersion.getVersion());
            assertEquals("6.4.4.Final", org.hibernate.Version.getVersionString());
            Products products = context.getBean(Products.class);
            var transaction = new TransactionTemplate(context.getBean(PlatformTransactionManager.class));
            Long id = transaction.execute(status -> products.saveAndFlush(new RuntimeProduct("雪")).id);
            assertNotNull(id);
            transaction.executeWithoutResult(status -> {
                RuntimeProduct product = products.findById(id).orElseThrow();
                product.name = "updated"; // Real Hibernate dirty checking, without an explicit save.
            });
            RuntimeProduct product = products.findByName("updated").orElseThrow();
            assertEquals(new BigDecimal("9007199254740993.12345678"), product.price);
            assertEquals(1, product.version);
            transaction.executeWithoutResult(status -> {
                products.saveAndFlush(new RuntimeProduct("rolled back")); status.setRollbackOnly();
            });
            assertTrue(products.findByName("rolled back").isEmpty());
            assertEquals(1, products.count());
            products.deleteById(id); assertEquals(0, products.count());
        }
    }
}
